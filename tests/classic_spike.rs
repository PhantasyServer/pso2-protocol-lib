//! Round-trip tests for the 14 classic packets recovered from the 2026-09-10 spike capture
//! (session 2026-09-10-2336-spike, classic 6.1253.3 NA client). Bytes are the exact decrypted
//! packets the client sent; each must now parse to its named variant and round-trip byte-for-byte.
use pso2packetlib::protocol::{Packet, PacketType, ProtocolRW};

#[test]
fn classic_spike_packets() {
    let cases: &[(&str, &[u8])] = &[
        ("Unk04BD", &[0x38, 0x00, 0x00, 0x00, 0x04, 0xbd, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x31, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x06, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xc6, 0x60, 0xd1, 0x00, 0x00, 0xe2, 0xd4, 0xa1, 0x5a, 0x29, 0x5a, 0x00, 0x00]),
        ("Unk073D", &[0x08, 0x00, 0x00, 0x00, 0x07, 0x3d, 0x00, 0x00]),
        ("Unk0741", &[0x08, 0x00, 0x00, 0x00, 0x07, 0x41, 0x00, 0x00]),
        ("Unk0F28", &[0x0c, 0x00, 0x00, 0x00, 0x0f, 0x28, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00]),
        ("Unk0FAA", &[0x10, 0x00, 0x00, 0x00, 0x0f, 0xaa, 0x00, 0x00, 0x02, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00]),
        ("Unk0FDA", &[0x0c, 0x00, 0x00, 0x00, 0x0f, 0xda, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00]),
        ("Unk1607", &[0x10, 0x00, 0x00, 0x00, 0x16, 0x07, 0x04, 0x00, 0x66, 0x62, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00]),
        ("Unk182E", &[0x10, 0x00, 0x00, 0x00, 0x18, 0x2e, 0x04, 0x00, 0x1a, 0x3d, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00]),
        ("Unk1C1E", &[0x10, 0x00, 0x00, 0x00, 0x1c, 0x1e, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00]),
        ("Unk1C46", &[0x14, 0x00, 0x00, 0x00, 0x1c, 0x46, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00]),
        ("Unk3472", &[0x08, 0x00, 0x00, 0x00, 0x34, 0x72, 0x00, 0x00]),
        ("Unk4816", &[0x08, 0x00, 0x00, 0x00, 0x48, 0x16, 0x00, 0x00]),
        ("Unk4900", &[0x08, 0x00, 0x00, 0x00, 0x49, 0x00, 0x00, 0x00]),
        ("Unk4F00", &[0x08, 0x00, 0x00, 0x00, 0x4f, 0x00, 0x00, 0x00]),
    ];
    for (name, bytes) in cases {
        let pkts = Packet::read(bytes, PacketType::NA)
            .unwrap_or_else(|e| panic!("{name}: read failed: {e:?}"));
        assert_eq!(pkts.len(), 1, "{name}: expected exactly one packet, got {}", pkts.len());
        assert!(!matches!(pkts[0], Packet::Unknown(_)), "{name}: still parsed as Unknown");
        let out = pkts[0].write(PacketType::NA);
        assert_eq!(&out[..], *bytes, "{name}: round-trip mismatch");
    }
}
